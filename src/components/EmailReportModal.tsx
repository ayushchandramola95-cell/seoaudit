"use client";

import { useState } from "react";
import {
  X,
  Mail,
  Send,
  CheckCircle2,
  Sparkles,
  Copy,
  Check,
  ExternalLink,
  AlertCircle,
  FileText,
  User,
} from "lucide-react";

interface EmailReportModalProps {
  isOpen: boolean;
  onClose: () => void;
  domain: string;
  score: number;
  grade: string;
  summary?: string;
  reportUrl?: string;
  topFixes?: Array<{ title: string; priority?: string }>;
}

export default function EmailReportModal({
  isOpen,
  onClose,
  domain,
  score,
  grade,
  summary,
  reportUrl,
  topFixes = [],
}: EmailReportModalProps) {
  const [recipientEmail, setRecipientEmail] = useState("");
  const [recipientName, setRecipientName] = useState("");
  const [customNote, setCustomNote] = useState(
    `Here is the latest technical SEO & Core Web Vitals executive audit snapshot for ${domain}.`
  );
  const [sending, setSending] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [sentResult, setSentResult] = useState<{
    deliveryId: string;
    timestamp: string;
    subject: string;
    textDigest: string;
    recipientEmail: string;
    providerMode?: string;
  } | null>(null);
  const [copiedDigest, setCopiedDigest] = useState(false);

  if (!isOpen) return null;

  const resolvedReportUrl =
    reportUrl || (typeof window !== "undefined" ? window.location.href : `https://seoseite.app/analyze?url=${domain}`);

  const emailSubject = `Executive SEO Audit Report: ${domain} (Score ${score}/100 • Grade ${grade})`;

  const buildEmailDigest = () => {
    const fixesListText =
      topFixes.length > 0
        ? topFixes
            .slice(0, 4)
            .map((f, i) => `${i + 1}. [${(f.priority || "HIGH").toUpperCase()}] ${f.title}`)
            .join("\n")
        : "1. Core Web Vitals (LCP & CLS) Optimization\n2. JSON-LD Structured Data Schema\n3. Canonical & Robots Directives Verification";

    return [
      `EXECUTIVE WEBSITE SEO AUDIT — ${domain.toUpperCase()}`,
      `============================================================`,
      recipientName ? `Prepared for: ${recipientName}` : null,
      `Overall SEO Health Score: ${score}/100 (Grade ${grade || "A"})`,
      `Generated on: ${new Date().toLocaleDateString()} at ${new Date().toLocaleTimeString()}`,
      customNote ? `\nConsultant Note:\n"${customNote}"` : null,
      summary ? `\nExecutive Diagnostic Summary:\n${summary}` : null,
      `\nTop Prioritized Action Items:\n${fixesListText}`,
      `\nPermanent Interactive Report Link:\n${resolvedReportUrl}`,
      `\nGenerated by SeoSeite Intelligence Platform`,
    ]
      .filter(Boolean)
      .join("\n");
  };

  const handleOpenGmail = () => {
    const text = buildEmailDigest();
    const gmailUrl = `https://mail.google.com/mail/?view=cm&fs=1&to=${encodeURIComponent(
      recipientEmail
    )}&su=${encodeURIComponent(emailSubject)}&body=${encodeURIComponent(text)}`;
    window.open(gmailUrl, "_blank", "noopener,noreferrer");
  };

  const handleOpenOutlook = () => {
    const text = buildEmailDigest();
    const outlookUrl = `https://outlook.live.com/mail/0/deeplink/compose?to=${encodeURIComponent(
      recipientEmail
    )}&subject=${encodeURIComponent(emailSubject)}&body=${encodeURIComponent(text)}`;
    window.open(outlookUrl, "_blank", "noopener,noreferrer");
  };

  const handleOpenMailto = () => {
    const text = buildEmailDigest();
    window.location.href = `mailto:${encodeURIComponent(recipientEmail)}?subject=${encodeURIComponent(
      emailSubject
    )}&body=${encodeURIComponent(text)}`;
  };

  const handleCopyDigest = async () => {
    const text = sentResult?.textDigest || buildEmailDigest();
    try {
      await navigator.clipboard.writeText(text);
    } catch {
      const ta = document.createElement("textarea");
      ta.value = text;
      document.body.appendChild(ta);
      ta.select();
      document.execCommand("copy");
      document.body.removeChild(ta);
    }
    setCopiedDigest(true);
    setTimeout(() => setCopiedDigest(false), 2400);
  };

  const handleSendEmail = async (e: React.FormEvent) => {
    e.preventDefault();
    setError(null);
    setSending(true);

    try {
      const res = await fetch("/api/report/email", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          recipientEmail,
          recipientName,
          domain,
          score,
          grade,
          summary,
          customNote,
          reportUrl: resolvedReportUrl,
          topFixes,
        }),
      });

      const data = await res.json();
      if (!res.ok || !data.success) {
        throw new Error(data.error || "Unable to send email report.");
      }

      setSentResult({
        deliveryId: data.deliveryId,
        timestamp: data.timestamp,
        subject: data.subject,
        textDigest: data.textDigest,
        recipientEmail: data.recipientEmail,
        providerMode: data.providerMode,
      });
    } catch (err: unknown) {
      setError((err as Error)?.message || "Unexpected error while sending report.");
    } finally {
      setSending(false);
    }
  };

  const handleResetAndClose = () => {
    setSentResult(null);
    setError(null);
    onClose();
  };

  return (
    <div
      className="fixed inset-0 z-50 bg-slate-900/60 backdrop-blur-xs flex items-center justify-center p-4 print:hidden animate-in fade-in duration-150"
      onClick={handleResetAndClose}
    >
      <div
        className="bg-white border border-slate-200 rounded-2xl max-w-xl w-full overflow-hidden shadow-2xl text-slate-900"
        onClick={(e) => e.stopPropagation()}
      >
        {/* Modal Header */}
        <div className="px-6 py-4 bg-slate-900 text-white flex items-center justify-between">
          <div className="flex items-center gap-2.5">
            <div className="w-8 h-8 rounded-lg bg-blue-600 flex items-center justify-center text-white">
              <Mail className="w-4 h-4" />
            </div>
            <div>
              <h3 className="text-sm font-bold">Email Executive Audit Report</h3>
              <p className="text-[11px] text-slate-400">Dispatch audit digest to client, team, or stakeholders</p>
            </div>
          </div>
          <button
            type="button"
            onClick={handleResetAndClose}
            className="text-slate-400 hover:text-white p-1 transition-colors cursor-pointer"
          >
            <X className="w-4 h-4" />
          </button>
        </div>

        {sentResult ? (
          <div className="p-6 space-y-4">
            <div className="p-4 rounded-xl bg-emerald-50 border border-emerald-200 flex items-start gap-3">
              <CheckCircle2 className="w-5 h-5 text-emerald-600 shrink-0 mt-0.5" />
              <div className="text-xs">
                <div className="font-bold text-emerald-950 text-sm">
                  {sentResult.providerMode === "resend_live"
                    ? "Executive Report Dispatched via Live Mail Server!"
                    : "Executive Report Digest Prepared!"}
                </div>
                <p className="text-emerald-800 mt-0.5">
                  Target recipient: <span className="font-mono font-bold">{sentResult.recipientEmail}</span> • Message ID{" "}
                  <span className="font-mono">{sentResult.deliveryId}</span>
                </p>
              </div>
            </div>

            {/* If no live Resend key was in server, offer immediate 1-click webmail dispatch */}
            {sentResult.providerMode !== "resend_live" && (
              <div className="p-3.5 bg-blue-50/80 rounded-xl border border-blue-200 space-y-2">
                <div className="text-xs font-bold text-blue-950 flex items-center gap-1.5">
                  <Send className="w-3.5 h-3.5 text-blue-600" />
                  <span>Send Immediately in 1-Click:</span>
                </div>
                <p className="text-[11px] text-blue-800">
                  Open your email app with the recipient, subject, and full executive report already filled out:
                </p>
                <div className="flex items-center gap-2 flex-wrap pt-1">
                  <button
                    type="button"
                    onClick={handleOpenGmail}
                    className="inline-flex items-center gap-1.5 px-3 py-1.5 rounded-lg text-xs font-bold bg-white hover:bg-slate-50 text-rose-700 border border-rose-200 shadow-2xs transition-colors cursor-pointer"
                  >
                    <span>Send via Gmail (Web)</span>
                    <ExternalLink className="w-3 h-3 text-rose-500" />
                  </button>
                  <button
                    type="button"
                    onClick={handleOpenOutlook}
                    className="inline-flex items-center gap-1.5 px-3 py-1.5 rounded-lg text-xs font-bold bg-white hover:bg-slate-50 text-sky-700 border border-sky-200 shadow-2xs transition-colors cursor-pointer"
                  >
                    <span>Send via Outlook (Web)</span>
                    <ExternalLink className="w-3 h-3 text-sky-500" />
                  </button>
                  <button
                    type="button"
                    onClick={handleOpenMailto}
                    className="inline-flex items-center gap-1.5 px-3 py-1.5 rounded-lg text-xs font-semibold bg-white hover:bg-slate-50 text-slate-700 border border-slate-200 shadow-2xs transition-colors cursor-pointer"
                  >
                    <span>Open in Default Mail App</span>
                  </button>
                </div>
              </div>
            )}

            <div>
              <div className="flex items-center justify-between mb-1.5">
                <span className="text-xs font-bold text-slate-700 flex items-center gap-1.5">
                  <FileText className="w-3.5 h-3.5 text-blue-600" />
                  Compiled Email Content
                </span>
                <button
                  type="button"
                  onClick={handleCopyDigest}
                  className="inline-flex items-center gap-1 text-[11px] font-semibold text-blue-600 hover:text-blue-700 cursor-pointer"
                >
                  {copiedDigest ? <Check className="w-3 h-3 text-emerald-600" /> : <Copy className="w-3 h-3" />}
                  <span>{copiedDigest ? "Copied to Clipboard!" : "Copy Full Text"}</span>
                </button>
              </div>
              <pre className="p-3.5 rounded-xl bg-slate-950 text-slate-200 font-mono text-[11px] leading-relaxed overflow-x-auto max-h-48 whitespace-pre-wrap border border-slate-800">
                {sentResult.textDigest}
              </pre>
            </div>

            <div className="flex items-center justify-between gap-2 pt-2 border-t border-slate-200">
              <button
                type="button"
                onClick={() => setSentResult(null)}
                className="px-3 py-2 rounded-lg text-xs font-semibold text-slate-600 hover:bg-slate-100 cursor-pointer"
              >
                Send Another Email
              </button>
              <button
                type="button"
                onClick={handleResetAndClose}
                className="px-4 py-2 rounded-lg text-xs font-bold bg-blue-600 hover:bg-blue-700 text-white cursor-pointer"
              >
                Done
              </button>
            </div>
          </div>
        ) : (
          <form onSubmit={handleSendEmail} className="p-6 space-y-4 text-xs">
            {error && (
              <div className="p-3.5 rounded-xl bg-amber-50 border border-amber-200 text-amber-900 space-y-2">
                <div className="flex items-center gap-2 font-bold text-xs">
                  <AlertCircle className="w-4 h-4 text-amber-600 shrink-0" />
                  <span>Email Provider Status</span>
                </div>
                <p className="text-[11px] text-amber-800 leading-relaxed">
                  {error}
                </p>
                <div className="pt-1 flex items-center gap-2 flex-wrap">
                  <button
                    type="button"
                    onClick={handleOpenGmail}
                    className="inline-flex items-center gap-1.5 px-3 py-1.5 rounded-lg text-xs font-bold bg-white hover:bg-rose-50 text-rose-700 border border-rose-200 shadow-2xs transition-colors cursor-pointer"
                  >
                    <Mail className="w-3 h-3 text-rose-500" />
                    <span>Send via Gmail (Web)</span>
                    <ExternalLink className="w-3 h-3 text-rose-500" />
                  </button>
                  <button
                    type="button"
                    onClick={handleOpenOutlook}
                    className="inline-flex items-center gap-1.5 px-3 py-1.5 rounded-lg text-xs font-bold bg-white hover:bg-sky-50 text-sky-700 border border-sky-200 shadow-2xs transition-colors cursor-pointer"
                  >
                    <Mail className="w-3 h-3 text-sky-500" />
                    <span>Send via Outlook (Web)</span>
                    <ExternalLink className="w-3 h-3 text-sky-500" />
                  </button>
                </div>
              </div>
            )}

            {/* Target snapshot banner */}
            <div className="p-3.5 bg-slate-50 rounded-xl border border-slate-200 flex items-center justify-between">
              <div>
                <div className="text-[10px] font-bold uppercase tracking-wider text-slate-400">
                  Target Domain Snapshot
                </div>
                <div className="text-sm font-extrabold text-slate-900 font-mono mt-0.5">{domain}</div>
              </div>
              <div className="flex items-center gap-2">
                <span className="px-2.5 py-1 rounded-lg bg-blue-600 text-white font-mono font-bold text-xs">
                  {score}/100
                </span>
                <span className="px-2.5 py-1 rounded-lg bg-emerald-50 text-emerald-700 border border-emerald-200 font-bold text-xs">
                  Grade {grade}
                </span>
              </div>
            </div>

            {/* Recipient inputs */}
            <div className="grid grid-cols-1 sm:grid-cols-2 gap-3">
              <div>
                <label className="font-semibold text-slate-700 block mb-1">
                  Recipient Email <span className="text-rose-500">*</span>
                </label>
                <div className="flex items-center gap-2 border border-slate-200 rounded-lg px-3 py-2 focus-within:border-blue-600 bg-white">
                  <Mail className="w-3.5 h-3.5 text-slate-400 shrink-0" />
                  <input
                    type="email"
                    required
                    value={recipientEmail}
                    onChange={(e) => setRecipientEmail(e.target.value)}
                    placeholder="client@company.com"
                    className="w-full text-xs text-slate-900 focus:outline-none"
                  />
                </div>
              </div>

              <div>
                <label className="font-semibold text-slate-700 block mb-1">Recipient / Client Name</label>
                <div className="flex items-center gap-2 border border-slate-200 rounded-lg px-3 py-2 focus-within:border-blue-600 bg-white">
                  <User className="w-3.5 h-3.5 text-slate-400 shrink-0" />
                  <input
                    type="text"
                    value={recipientName}
                    onChange={(e) => setRecipientName(e.target.value)}
                    placeholder="e.g. Marketing Lead"
                    className="w-full text-xs text-slate-900 focus:outline-none"
                  />
                </div>
              </div>
            </div>

            {/* Custom note */}
            <div>
              <label className="font-semibold text-slate-700 block mb-1">Executive Note</label>
              <textarea
                rows={3}
                value={customNote}
                onChange={(e) => setCustomNote(e.target.value)}
                placeholder="Add a personalized note..."
                className="w-full border border-slate-200 rounded-lg p-2.5 text-xs text-slate-800 focus:outline-none focus:border-blue-600 leading-relaxed"
              />
            </div>

            {/* 1-Click Instant Dispatch Toolbar */}
            <div className="p-3 bg-slate-50 rounded-xl border border-slate-200 space-y-2">
              <div className="flex items-center justify-between">
                <span className="text-[11px] font-bold text-slate-700 flex items-center gap-1.5">
                  <Send className="w-3.5 h-3.5 text-blue-600" />
                  1-Click Instant Webmail Send:
                </span>
                <span className="text-[10px] text-slate-400">Pre-populates full audit report</span>
              </div>
              <div className="flex items-center gap-2 flex-wrap">
                <button
                  type="button"
                  onClick={handleOpenGmail}
                  className="inline-flex items-center gap-1.5 px-3 py-1.5 rounded-lg text-xs font-bold bg-white hover:bg-slate-100 text-rose-700 border border-rose-200 shadow-2xs transition-colors cursor-pointer"
                  title="Open Gmail with this audit report pre-filled"
                >
                  <Mail className="w-3 h-3 text-rose-500" />
                  <span>Send via Gmail</span>
                  <ExternalLink className="w-2.5 h-2.5 text-rose-400" />
                </button>
                <button
                  type="button"
                  onClick={handleOpenOutlook}
                  className="inline-flex items-center gap-1.5 px-3 py-1.5 rounded-lg text-xs font-bold bg-white hover:bg-slate-100 text-sky-700 border border-sky-200 shadow-2xs transition-colors cursor-pointer"
                  title="Open Outlook Web with this audit report pre-filled"
                >
                  <Mail className="w-3 h-3 text-sky-500" />
                  <span>Send via Outlook</span>
                  <ExternalLink className="w-2.5 h-2.5 text-sky-400" />
                </button>
                <button
                  type="button"
                  onClick={handleCopyDigest}
                  className="inline-flex items-center gap-1.5 px-2.5 py-1.5 rounded-lg text-xs font-semibold bg-white hover:bg-slate-100 text-slate-700 border border-slate-200 shadow-2xs transition-colors cursor-pointer"
                >
                  {copiedDigest ? <Check className="w-3 h-3 text-emerald-600" /> : <Copy className="w-3 h-3 text-slate-500" />}
                  <span>{copiedDigest ? "Copied!" : "Copy Text"}</span>
                </button>
              </div>
            </div>

            {/* Scope pill */}
            <div className="p-2.5 bg-blue-50/60 rounded-xl border border-blue-100 flex items-center justify-between text-[11px] text-blue-900">
              <span className="flex items-center gap-1.5">
                <Sparkles className="w-3.5 h-3.5 text-blue-600 shrink-0" />
                <span>Includes 0–100 score, AI diagnostic summary &amp; permanent report link</span>
              </span>
              <span className="font-mono font-bold">{score}/100</span>
            </div>

            {/* Form Footer */}
            <div className="pt-2 flex items-center justify-between gap-2 border-t border-slate-200">
              <button
                type="button"
                onClick={handleOpenMailto}
                className="inline-flex items-center gap-1.5 px-3 py-2 rounded-lg text-xs font-semibold text-slate-600 hover:bg-slate-100 cursor-pointer"
              >
                <ExternalLink className="w-3.5 h-3.5" /> Open in Mail App
              </button>

              <div className="flex items-center gap-2">
                <button
                  type="button"
                  onClick={handleResetAndClose}
                  className="px-3.5 py-2 rounded-lg text-xs font-semibold text-slate-600 hover:bg-slate-100 cursor-pointer"
                >
                  Cancel
                </button>
                <button
                  type="submit"
                  disabled={sending}
                  className="px-4 py-2 rounded-lg text-xs font-bold bg-blue-600 hover:bg-blue-700 disabled:opacity-60 text-white flex items-center gap-1.5 cursor-pointer shadow-xs"
                >
                  <Send className="w-3.5 h-3.5" />
                  <span>{sending ? "Dispatching..." : "Send via Server API"}</span>
                </button>
              </div>
            </div>
          </form>
        )}
      </div>
    </div>
  );
}
