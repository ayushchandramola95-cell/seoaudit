import { NextRequest, NextResponse } from "next/server";
import nodemailer from "nodemailer";

interface EmailReportPayload {
  recipientEmail: string;
  recipientName?: string;
  domain: string;
  score: number;
  grade: string;
  summary?: string;
  customNote?: string;
  reportUrl?: string;
  topFixes?: Array<{ title: string; priority?: string }>;
}

function isValidEmail(email: string): boolean {
  return /^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email.trim());
}

export async function POST(request: NextRequest) {
  try {
    const body = (await request.json()) as EmailReportPayload;
    const {
      recipientEmail,
      recipientName,
      domain,
      score,
      grade,
      summary,
      customNote,
      reportUrl,
      topFixes = [],
    } = body;

    if (!recipientEmail || !isValidEmail(recipientEmail)) {
      return NextResponse.json(
        {
          success: false,
          error: "Please provide a valid recipient email address.",
        },
        { status: 400 }
      );
    }

    if (!domain || typeof score !== "number") {
      return NextResponse.json(
        {
          success: false,
          error: "Missing required audit report parameters (domain, score).",
        },
        { status: 400 }
      );
    }

    const subject = `Executive SEO Audit Report: ${domain} (Score ${score}/100 • Grade ${grade || "A"})`;
    const deliveryId = `msg_${Date.now().toString(36)}_${Math.random().toString(36).slice(2, 7)}`;
    const timestamp = new Date().toISOString();

    const fixesListText =
      topFixes.length > 0
        ? topFixes
            .slice(0, 4)
            .map((f, i) => `${i + 1}. [${(f.priority || "HIGH").toUpperCase()}] ${f.title}`)
            .join("\n")
        : "1. Core Web Vitals (LCP & CLS) Optimization\n2. JSON-LD Structured Data Schema\n3. Canonical & Robots Directives Verification";

    const textDigest = [
      `EXECUTIVE WEBSITE SEO AUDIT — ${domain.toUpperCase()}`,
      `============================================================`,
      recipientName ? `Prepared for: ${recipientName}` : null,
      `Overall SEO Health Score: ${score}/100 (Grade ${grade || "A"})`,
      `Generated on: ${new Date(timestamp).toLocaleString()}`,
      customNote ? `\nConsultant Note:\n"${customNote}"` : null,
      summary ? `\nExecutive Diagnostic Summary:\n${summary}` : null,
      `\nTop Prioritized Action Items:\n${fixesListText}`,
      reportUrl ? `\nPermanent Interactive Report Link:\n${reportUrl}` : null,
      `\nGenerated by SeoSeite Intelligence Engine`,
    ]
      .filter(Boolean)
      .join("\n");

    const htmlFixesList =
      topFixes.length > 0
        ? topFixes
            .slice(0, 4)
            .map(
              (f) =>
                `<li style="margin-bottom: 8px;"><strong>[${(f.priority || "HIGH").toUpperCase()}]</strong> ${f.title}</li>`
            )
            .join("")
        : `<li>Review Core Web Vitals (LCP, CLS, FID) optimization</li><li>Verify JSON-LD structured data coverage</li><li>Audit canonical & robots directives</li>`;

    const htmlDigest = `
<!DOCTYPE html>
<html>
<head>
  <meta charset="utf-8">
  <title>${subject}</title>
</head>
<body style="font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, Helvetica, Arial, sans-serif; background-color: #f8fafc; margin: 0; padding: 24px; color: #1e293b;">
  <div style="max-width: 600px; margin: 0 auto; background: #ffffff; border-radius: 16px; border: 1px solid #e2e8f0; overflow: hidden; box-shadow: 0 4px 6px -1px rgba(0,0,0,0.05);">
    <div style="background-color: #0f172a; padding: 24px; color: #ffffff;">
      <div style="font-size: 11px; font-weight: 700; text-transform: uppercase; letter-spacing: 0.1em; color: #38bdf8;">Technical SEO Executive Audit</div>
      <h1 style="font-size: 22px; font-weight: 900; margin: 6px 0 0 0; color: #ffffff;">${domain}</h1>
      ${recipientName ? `<div style="font-size: 12px; color: #94a3b8; margin-top: 4px;">Prepared for: ${recipientName}</div>` : ""}
    </div>

    <div style="padding: 24px;">
      <div style="display: flex; align-items: center; justify-content: space-between; background: #f1f5f9; padding: 16px 20px; border-radius: 12px; margin-bottom: 20px;">
        <div>
          <div style="font-size: 11px; font-weight: 700; color: #64748b; text-transform: uppercase;">SEO Health Score</div>
          <div style="font-size: 32px; font-weight: 900; color: #0f172a; line-height: 1;">${score}<span style="font-size: 14px; font-weight: 600; color: #64748b;"> / 100</span></div>
        </div>
        <div style="background: #10b981; color: #ffffff; font-weight: 800; font-size: 14px; padding: 6px 14px; border-radius: 9999px;">
          Grade ${grade || "A"}
        </div>
      </div>

      ${customNote ? `<div style="background: #eff6ff; border-left: 4px solid #3b82f6; padding: 12px 16px; border-radius: 4px; margin-bottom: 20px; font-size: 13px; color: #1e40af; line-height: 1.5;"><strong>Consultant Note:</strong><br/>${customNote}</div>` : ""}

      ${summary ? `<div style="margin-bottom: 20px;"><h3 style="font-size: 13px; font-weight: 700; text-transform: uppercase; color: #475569; margin: 0 0 8px 0;">Executive Summary</h3><p style="font-size: 13px; line-height: 1.6; color: #334155; margin: 0;">${summary}</p></div>` : ""}

      <div style="margin-bottom: 24px;">
        <h3 style="font-size: 13px; font-weight: 700; text-transform: uppercase; color: #475569; margin: 0 0 10px 0;">Top Priority Action Items</h3>
        <ul style="font-size: 13px; line-height: 1.5; color: #334155; padding-left: 20px; margin: 0;">
          ${htmlFixesList}
        </ul>
      </div>

      ${reportUrl ? `<div style="text-align: center; margin-top: 24px; padding-top: 20px; border-top: 1px solid #f1f5f9;"><a href="${reportUrl}" style="display: inline-block; background-color: #2563eb; color: #ffffff; text-decoration: none; font-size: 13px; font-weight: 700; padding: 12px 24px; border-radius: 8px;">View Full Interactive Audit Report &rarr;</a></div>` : ""}
    </div>

    <div style="background-color: #f8fafc; padding: 16px 24px; font-size: 11px; color: #94a3b8; text-align: center; border-top: 1px solid #f1f5f9;">
      Generated by SeoSeite Platform &bull; Delivery ID: ${deliveryId}
    </div>
  </div>
</body>
</html>
    `;

    // 1. Check for Gmail / Custom SMTP credentials
    const smtpUser = process.env.SMTP_USER;
    const smtpPass = process.env.SMTP_PASS;
    const smtpHost = process.env.SMTP_HOST || "smtp.gmail.com";
    const smtpPort = Number(process.env.SMTP_PORT) || 465;

    if (smtpUser && smtpPass) {
      try {
        const transporter = nodemailer.createTransport({
          host: smtpHost,
          port: smtpPort,
          secure: smtpPort === 465,
          auth: {
            user: smtpUser,
            pass: smtpPass,
          },
        });

        await transporter.sendMail({
          from: process.env.SMTP_FROM || `"SeoSeite Intelligence" <${smtpUser}>`,
          to: recipientEmail.trim(),
          subject,
          text: textDigest,
          html: htmlDigest,
        });

        return NextResponse.json({
          success: true,
          delivered: true,
          providerMode: "smtp_live",
          deliveryId,
          timestamp,
          recipientEmail: recipientEmail.trim(),
          subject,
          textDigest,
        });
      } catch (smtpErr: unknown) {
        return NextResponse.json(
          {
            success: false,
            error: `SMTP dispatch failed: ${(smtpErr as Error)?.message || "Authentication error."}`,
            textDigest,
            subject,
          },
          { status: 500 }
        );
      }
    }

    // 2. Check for Resend API Key
    const resendApiKey = process.env.RESEND_API_KEY;
    if (resendApiKey) {
      try {
        const resendRes = await fetch("https://api.resend.com/emails", {
          method: "POST",
          headers: {
            Authorization: `Bearer ${resendApiKey}`,
            "Content-Type": "application/json",
          },
          body: JSON.stringify({
            from: process.env.EMAIL_FROM || "SeoSeite Audit <onboarding@resend.dev>",
            to: [recipientEmail.trim()],
            subject,
            text: textDigest,
            html: htmlDigest,
          }),
        });

        if (resendRes.ok) {
          return NextResponse.json({
            success: true,
            delivered: true,
            providerMode: "resend_live",
            deliveryId,
            timestamp,
            recipientEmail: recipientEmail.trim(),
            subject,
            textDigest,
          });
        }
      } catch (resendErr: unknown) {
        return NextResponse.json(
          {
            success: false,
            error: `Resend dispatch failed: ${(resendErr as Error)?.message}`,
            textDigest,
            subject,
          },
          { status: 500 }
        );
      }
    }

    // 3. No server email provider configured: Return honest, structured response
    return NextResponse.json(
      {
        success: false,
        errorType: "PROVIDER_NOT_CONFIGURED",
        error:
          "No server email provider configured in .env.local (RESEND_API_KEY or SMTP_USER/SMTP_PASS). Please use the 1-click 'Send via Gmail' button below to send immediately from your Gmail account, or add credentials to .env.local.",
        deliveryId,
        timestamp,
        recipientEmail: recipientEmail.trim(),
        subject,
        textDigest,
      },
      { status: 422 }
    );
  } catch (err: unknown) {
    return NextResponse.json(
      {
        success: false,
        error: (err as Error)?.message || "Failed to dispatch executive email report.",
      },
      { status: 500 }
    );
  }
}
